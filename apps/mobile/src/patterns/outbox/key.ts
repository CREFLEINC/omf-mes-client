/**
 * 멱등키를 만든다.
 *
 * 계약이 형식을 UUID 로 못 박았다. 다른 모양이면 서버가 요청 자체를 거부한다.
 *
 * 부를 때마다 다른 값이다. 내용으로 키를 지으면 다른 대상에 같은 값을 보낼 때 화면 부품이
 * 같은 키를 만들고, 뒤 요청이 조용히 사라지면서 화면은 성공을 본다. 같은 대상에 같은 일을
 * 일부러 두 번 하는 경우도 마찬가지로 앞엣것에 흡수된다.
 *
 * 중복을 막는 것은 담아 둔 키를 재전송에 그대로 다시 쓰는 자리다.
 */
export const createIdempotencyKey = (): string => crypto.randomUUID();
