import { signal } from './scan-feedback';

/**
 * 스캔 오류를 알린다(공유계약 D-2). 장갑을 낀 채 단말을 허리에 매달고 읽는
 * 작업이라 화면을 보고 있지 않을 수 있다.
 *
 * 이제 소리만이 아니다 - 거절 신호(`signal('reject')`)로 진동과 빨간 테두리를 함께 낸다.
 * 이 이름은 이미 여러 화면이 부르고 있어 그대로 둔다.
 *
 * 소리를 낼 수 없는 환경에서도 던지지 않는다 — 인라인 오류가 이미 나가 있으므로
 * 여기서 예외가 오르면 보이는 경고까지 함께 끊긴다.
 */
export const playErrorTone = (): void => {
  signal('reject');
};
