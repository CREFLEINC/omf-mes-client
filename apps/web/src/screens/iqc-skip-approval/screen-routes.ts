/**
 * **화면 ID → 이 앱의 주소.** 계약이 프런트에 두라고 지시한 매핑 **하나**다 —
 * 「대상 유형 → 화면」 매핑은 만들지 않는다(그것이 금지된 쪽이다).
 *
 * ---
 *
 * **지금은 빈 표다.** 근거 둘.
 *
 * | # | 사실 |
 * | :-: | --- |
 * | ① | **문서 하나를 지목해 여는 주소 규약이 계약에도 이 저장소에도 없다** — 화면만 열면 「열었더니 그 문서가 아니다」가 된다 |
 * | ② | 이 앱에 선 업무 화면들은 **조건으로 여는 목록 화면**이라 특정 문서로 이동시킬 수단 자체가 없다 |
 *
 * 그래서 빈 표가 「아직 없다」의 정직한 모습이다. 그럴듯한 경로를 지어 넣으면 사용자는
 * 「열기」를 누르고 엉뚱한 자리에 도착하며, 그 값이 화면 코드보다 오래 남아 규약처럼 굳는다.
 *
 * **이 화면에서 줄 하나를 넣고 싶은 유혹이 특히 크다** — 대상이 입하 계열일 가능성이 높고
 * 그 목록 화면이 이 앱에 이미 있다. 넣지 않는 근거가 ②다. 그 판정을 시험이 못 박는다.
 *
 * **줄이 생기면 그것만으로 열기가 살아난다.** 판정은 이 표를 읽는 자리 하나(`target.ts`)에
 * 있고 잠금을 상수로 굳혀 두지 않았다 — 자리표시를 「영영 죽은 가지」로 만들지 않기 위해서다.
 *
 * 이 화면이 소유한다 — 다른 화면 슬라이스의 같은 이름 파일을 참조하지 않는다.
 */

/** 화면 ID를 열쇠로 하는 주소 표. `screenId`는 계약이 내려 주는 값이라 키를 좁히지 않는다. */
export type ScreenRouteTable = Readonly<Record<string, string>>;

/** 화면 ID → 주소. **비어 있는 것이 지금의 사실이다.** */
export const SCREEN_ROUTES: ScreenRouteTable = {};

/**
 * 그 화면 ID가 이 앱의 어느 주소인가. 표에 없으면 `null`이다 — **없음을 값으로 낸다.**
 *
 * **표에 넣지 않은 열쇠는 표에 없는 것이다.** 막을 것이 둘이고 둘 다 서버가 보낸 값이 그대로
 * 열쇠가 되는 데서 온다.
 *
 * | 막는 것 | 그대로 두면 |
 * | --- | --- |
 * | **빈 화면 ID** | 계약이 `screenId`를 선택 필드로 두어 빈 문자열이 스키마를 통과한다. 표에 실수로 들어간 빈 열쇠가 **아무 대상이나** 열게 된다 |
 * | **프로토타입에서 온 열쇠** | 표가 객체 리터럴이라 `toString`·`constructor`가 **함수**를 낸다. 없음을 뜻하는 `null`이 아니라서 걸러지지 않고, 「열기」가 살아 있는 버튼으로 서서 누르면 그 함수가 경로 자리에 실려 간다 |
 *
 * 타입은 이 둘을 막지 못한다 — `Record<string, string>`이 모든 문자열 열쇠가 문자열 값을
 * 낸다고 약속한 것처럼 보이지만, 그 약속은 **표에 넣은 열쇠에만** 걸린다.
 */
export const screenPathOf = (screenId: string, routes: ScreenRouteTable): string | null =>
  screenId === '' || !Object.hasOwn(routes, screenId) ? null : (routes[screenId] ?? null);
