import type { CodeGroup } from './types';

/**
 * **W-06-04 판정유형 코드 마스터가 갖는 판정유형 지식 전부**가 이 파일에 있다(omf-mes-client#16).
 *
 * 이 화면은 전용 자원이 아니다 — 판정유형은 코드값 하나이고 계약에 전용 경로가 없어,
 * 공통코드의 **코드값 편집기를 이 코드그룹으로 고정해 여는 진입점**이다. 그래서 이 파일이 아는 것은
 * 「어느 코드그룹인가」 하나뿐이고, 값 목록·통제 속성·이력은 여기에 없다.
 *
 * 판정유형이 자기 속성(출고 차단 등)을 갖는 자원이 되면 이 파일과 화면 파일 둘만 옮기면 된다.
 */

/**
 * 판정유형 코드 그룹의 **그룹코드**. 이 화면이 고정해 여는 그룹을 특정하는 유일한 값이다.
 *
 * **번호(`codeGroupId`)를 쓰지 않는다** — 번호는 자료가 만들어질 때 정해져 환경마다 다르다.
 * 그룹코드로 조회한 뒤 목록에서 정확히 일치하는 것을 고른다.
 *
 * ⚠ **값이 아직 확정되지 않았다**(omf-mes-client#16에서 확인 중). 확정되면 **이 한 줄만** 고친다.
 * 그때까지도 화면은 사실을 정확히 안내한다 — 찾지 못하면 「그룹을 찾지 못했습니다」를 내고
 * 엉뚱한 그룹이나 빈 표를 보이지 않는다.
 */
export const JUDGMENT_TYPE_GROUP_CODE: string = 'JUDGMENT_TYPE';

/**
 * 알려진 판정유형 코드의 자리표시 상수. **비어 있다 — 값을 지어내지 않는다.**
 *
 * 목록의 정본은 서버(코드값 조회 결과)다. 코드에 적으면 ① 화면이 서버와 다른 답을 낼 수 있고
 * ② 값이 늘 때 두 곳을 고쳐야 하며 ③ 이 목록으로 서버 응답을 거르려는 유혹이 생긴다.
 *
 * **화면은 이 상수로 서버 목록을 거르지 않는다.** 여기 없는 코드도 그대로 보인다.
 * 비어 있어도 자리를 남기는 것은, 확정됐을 때 고칠 곳이 한눈에 보이게 하기 위해서다.
 */
export const KNOWN_JUDGMENT_TYPE_CODES: readonly string[] = [];

/** 판정유형 목록이 아직 확정되지 않았는가. 화면은 이때 「임시 목록」 안내를 낸다. */
export const isProvisionalJudgmentTypeList = (): boolean => KNOWN_JUDGMENT_TYPE_CODES.length === 0;

/**
 * 조회한 코드그룹 목록에서 판정유형 코드 그룹을 고른다. 없으면 `null`이다.
 *
 * **정확 일치만 고른다.** 이 화면에서 가장 나쁜 결함은 「엉뚱한 그룹이 열려 다른 업무의 코드값을
 * 판정유형인 줄 알고 고치는 것」이라, 판정을 느슨하게 할 수 있는 세 자리를 전부 막는다.
 *
 * - **부분 일치를 쓰지 않는다** — 조회의 `q`가 부분 검색이라 이름이 겹치는 다른 그룹이 함께 온다
 * - **대소문자를 접지 않는다** — 접으면 대소문자만 다른 별개 그룹이 걸린다
 * - **그룹명을 보지 않는다** — 그룹명은 사람이 고쳐 쓰는 표시용 이름이라 판정 근거가 못 된다
 *
 * 못 찾았을 때 **첫 항목으로 대신하지 않는다.** 「없음」은 화면이 정확히 안내할 수 있는 정상 상태이고,
 * 첫 항목을 쓰면 그 순간부터 화면이 조용히 다른 그룹을 편집한다.
 *
 * 사용 여부는 판정 근거가 아니다 — 미사용 그룹도 찾아내야 그 사실을 안내할 수 있다.
 */
export const findJudgmentTypeGroup = (groups: readonly CodeGroup[]): CodeGroup | null =>
  groups.find((group) => group.groupCode === JUDGMENT_TYPE_GROUP_CODE) ?? null;
