/**
 * 긴급을 뜻하는 W/O 유형 코드.
 *
 * ⛔ **값을 이 슬라이스 안 한 곳에만 둔다.** 조회 조건과 줄 표식이 각자 문자열을 박으면 값이
 * 바뀔 때 한쪽만 고쳐지고, 그 어긋남은 오류 없이 조용하다 — 화면은 「긴급」이라 적어 놓고
 * 긴급이 아닌 지시를 보이게 된다.
 *
 * ⛔ **다른 화면 슬라이스의 상수를 참조하지 않는다.** 슬라이스는 서로 import 하지 않고
 * 사본을 소유한다 — 여기서는 발행 화면(`emergency-work-order`)이 같은 값을 따로 갖는다.
 *
 * 값 집합은 셋이다 — 양산 · **긴급** · 재작업. 이 화면은 그중 하나만 쓴다(설계 근거:
 * omf-mes#259 회신 · 반영 omf-mes#274).
 */
export const EMERGENCY_WORK_ORDER_TYPE_CODE = 'EMERGENCY';

/**
 * 유형 코드를 아는가.
 *
 * ⚠ **값이 정해진 뒤에도 남겨 둔다.** 어떤 경위로든 빈 값이 흘러들면 **조회를 열어서는 안
 * 된다** — 조건이 빠진 질의는 긴급이 아닌 지시까지 돌려주고, 화면은 그것들을 긴급으로
 * 보인다. 상수를 채운 것과 「빈 값으로는 못 묻는다」는 다른 보장이다.
 *
 * 상수를 직접 읽지 않고 인자로도 받는 이유는 그 닫힌 쪽 경로를 감지기가 확인할 수 있게
 * 하기 위해서다.
 */
export const isEmergencyTypeCodeKnown = (code: string = EMERGENCY_WORK_ORDER_TYPE_CODE): boolean =>
  code.trim() !== '';
