/**
 * 로그인 실패의 화면 갈래 — **셋뿐이다**(#1034).
 *
 * 앞 회차는 다섯 갈래(자격 불일치·잠긴 계정·검증 실패·통신 실패·알 수 없음)에 남은 시도
 * 횟수와 잠금 임계값 안내까지 얹고 있었다. 그 세밀함이 값을 내지 못해 접었지만, **잠긴
 * 계정은 남긴다** — 그것만 사용자가 할 조치가 다르다.
 *
 * **가르는 축은 「사용자가 무엇을 하면 풀리는가」다.**
 *
 * | 응답 | 갈래 | 사용자가 할 일 |
 * | --- | --- | --- |
 * | 401 | `credentials` | **값을 고친다** — 서버가 「이 자격은 아니다」라고 답한 유일한 자리 |
 * | 423 | `locked` | **사람에게 요청한다** — 스스로 풀 수 없다 |
 * | 그 밖 전부 | `server` | **기다렸다 다시 보낸다** — 고칠 값도 요청할 곳도 없다 |
 *
 * ⛔ **모르는 응답을 「자격이 맞지 않는다」로 꾸미지 않는다.** 그 문장은 자격이 틀렸다는
 * **주장**이라, 서버 장애나 권한 문제에 붙이면 사용자가 맞는 자격을 의심하며 시도를 되풀이하다
 * 계정을 잠근다. 갈래를 줄이면서도 이 규율은 그대로 둔다 — 줄인 것은 갈래 수이지 이 판단이 아니다.
 *
 * ⛔ **잠긴 계정을 `server` 로 접지 않는다.** 접으면 「잠시 뒤 다시 시도하세요」와 「다시 시도」
 * 버튼이 서는데, 잠긴 계정에는 **다시 보내도 같은 답이 온다.** 하라고 한 일이 아무 소용이
 * 없는 화면이 되고, 정작 해야 할 일(관리자 요청)이 가려진다.
 *
 * **공통 정규화(`normalizeApiError`)를 쓰지 않는다** — 그쪽은 423 본문을 `ErrorResponse` 로 보아
 * **필드 오류처럼 분류한다.** 상태 코드로 가르는 이 규칙은 이 화면의 것이고, `patterns/` 에
 * 특정 화면 분기를 두지 않는다(`work-splitting.md`).
 */
export type LoginOutcome =
  /** 서버가 자격을 보고 거절했다(401). 값을 고쳐야 풀린다 */
  | { kind: 'credentials' }
  /** 실패가 쌓여 잠겼다(423). 스스로 풀 수 없다 — 문구가 관리자 요청을 가리킨다 */
  | { kind: 'locked' }
  /**
   * 그 밖의 모든 실패 — 응답이 없었거나, 서버가 자격 판정도 잠금도 아닌 이유로 거절했거나,
   * 이 앱의 코드가 던졌다.
   *
   * ⭐ **잡은 값이 있으면 함께 안고 간다**(`cause`). 이 갈래에는 응답이 아니라 **이 앱의 코드가
   * 던진 것**이 떨어지는 길이 있다(성공 되먹임의 예외 — `queries.ts`). 원인을 여기서 버리면
   * 그 결함이 「서버가 이상하다」로 보이고 어디에도 흔적이 남지 않는다.
   *
   * ⛔ **그리지 않는다.** 배너는 `kind` 만 본다 — 사용자에게 내부 오류를 보이지 않는다.
   */
  | { kind: 'server'; cause?: unknown };

/** 서버가 자격을 보고 거절한 상태 코드. 이 하나만 「로그인 정보 오류」가 된다. */
const CREDENTIALS_REJECTED = 401;

/**
 * 잠긴 계정의 상태 코드.
 *
 * **상태 코드로만 판정한다.** 계약이 423 본문에 코드 enum 을 주지 않았고(설명이 「실패가 쌓여
 * 잠겼다」뿐) 목 서버도 그 자리에 일반 오류 본문을 준다(실측). 본문 코드로 가르면 서버가
 * 문구만 바꿔도 갈래가 깨진다.
 */
const ACCOUNT_LOCKED = 423;

/**
 * 상태 코드에서 화면 갈래를 고른다.
 *
 * **본문을 보지 않는다.** 앞 회차는 401 본문의 `remainingAttempts` 와 400 본문의 오류 목록을
 * 꺼냈지만, 둘 다 그리지 않기로 했으므로 꺼낼 이유가 없다. 본문 형태에 기대지 않으면 서버·목·
 * 프록시가 계약과 다른 본문을 줄 때도 갈래가 흔들리지 않는다.
 */
export const toLoginOutcome = (status: number): LoginOutcome => {
  if (status === CREDENTIALS_REJECTED) return { kind: 'credentials' };
  if (status === ACCOUNT_LOCKED) return { kind: 'locked' };

  return { kind: 'server' };
};
