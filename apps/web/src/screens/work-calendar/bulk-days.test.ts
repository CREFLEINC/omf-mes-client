import { describe, expect, it } from 'vitest';

import { WEEKDAY_NUMBERS, expandDates, weekdayOf } from './bulk-days';

describe('weekdayOf', () => {
  /** 2026-08-01 은 토요일(6), 08-02 는 일요일(0). */
  it('요일을 읽는다', () => {
    expect(weekdayOf('2026-08-01')).toBe(6);
    expect(weekdayOf('2026-08-02')).toBe(0);
  });

  it.each(['2026-8-1', '20260801', '2026-13-01', '2026-02-30', ''])(
    '읽을 수 없는 %s 는 null 이다',
    (value) => {
      expect(weekdayOf(value)).toBeNull();
    },
  );
});

describe('expandDates', () => {
  /*
   * ⭐ **규칙이 아니라 날짜를 보낸다.** 화면이 세어 보인 그 목록을 그대로 보내므로,
   * 보인 수와 실제로 바뀌는 수가 갈리지 않는다.
   */
  it('요일을 고르지 않으면 기간 전체다', () => {
    expect(expandDates('2026-08-01', '2026-08-05', [])).toEqual([
      '2026-08-01',
      '2026-08-02',
      '2026-08-03',
      '2026-08-04',
      '2026-08-05',
    ]);
  });

  it('고른 요일만 편다', () => {
    /* 2026-08 의 일요일은 2·9·16·23·30 이다. */
    expect(expandDates('2026-08-01', '2026-08-31', [0])).toEqual([
      '2026-08-02',
      '2026-08-09',
      '2026-08-16',
      '2026-08-23',
      '2026-08-30',
    ]);
  });

  it('요일 여럿을 함께 편다', () => {
    expect(expandDates('2026-08-01', '2026-08-08', [0, 6])).toEqual([
      '2026-08-01',
      '2026-08-02',
      '2026-08-08',
    ]);
  });

  it('하루짜리 기간도 편다', () => {
    expect(expandDates('2026-08-15', '2026-08-15', [])).toEqual(['2026-08-15']);
  });

  /* 달과 해를 넘는 기간도 하루씩 이어져야 한다 — 연말에서 끊기면 안 된다. */
  it('해를 넘는 기간을 잇는다', () => {
    const dates = expandDates('2025-12-30', '2026-01-02', []);

    expect(dates).toEqual(['2025-12-30', '2025-12-31', '2026-01-01', '2026-01-02']);
  });

  /** 윤년 2월 29일이 빠지지 않는다. */
  it('윤일을 빠뜨리지 않는다', () => {
    expect(expandDates('2024-02-28', '2024-03-01', [])).toEqual([
      '2024-02-28',
      '2024-02-29',
      '2024-03-01',
    ]);
  });

  /*
   * ⛔ **읽을 수 없는 날짜나 뒤집힌 기간은 빈 목록이다** — 지어내지 않는다.
   * 화면은 그 0을 그대로 보이고 「바꿀 날이 없다」로 잠근다.
   */
  it.each([
    ['2026-08-10', '2026-08-01'],
    ['2026-08-01', '읽을 수 없음'],
    ['', '2026-08-01'],
    ['2026-02-30', '2026-03-01'],
  ])('%s ~ %s 는 빈 목록이다', (from, to) => {
    expect(expandDates(from, to, [])).toEqual([]);
  });

  it('기간 안에 고른 요일이 없으면 빈 목록이다', () => {
    /* 2026-08-03(월)~08-05(수) 안에 일요일은 없다. */
    expect(expandDates('2026-08-03', '2026-08-05', [0])).toEqual([]);
  });

  /* 한 해를 통째로 펴도 날 수가 맞아야 한다 — 하루가 겹치거나 건너뛰면 여기서 드러난다. */
  it('한 해를 하루도 겹치거나 빠뜨리지 않고 편다', () => {
    const dates = expandDates('2026-01-01', '2026-12-31', []);

    expect(dates).toHaveLength(365);
    expect(new Set(dates).size).toBe(365);
    expect(dates[0]).toBe('2026-01-01');
    expect(dates.at(-1)).toBe('2026-12-31');
  });

  it('윤년은 366일이다', () => {
    expect(expandDates('2024-01-01', '2024-12-31', [])).toHaveLength(366);
  });

  /** 계약 주석의 예 — 한 해의 일요일은 52~53일이다. */
  it('한 해의 일요일을 편다', () => {
    expect(expandDates('2026-01-01', '2026-12-31', [0])).toHaveLength(52);
  });
});

describe('WEEKDAY_NUMBERS', () => {
  it('0부터 6까지 일곱이다', () => {
    expect(WEEKDAY_NUMBERS).toEqual([0, 1, 2, 3, 4, 5, 6]);
  });
});
