/**
 * 단말 등록 패널만 **단말 화면에 맞춰 키운다**.
 *
 * ⭐ **왜 이 화면만인가.** POP 전체는 `patterns/pop-fit` 이 배율을 잡되 **줄이기만 한다**
 * (상한 1) — 화면 스펙이 `1024 × 768` 예산으로 그려져 있어 키우면 스펙이 정한 글자 크기
 * 관계가 깨지기 때문이다. 그런데 등록 패널은 예산을 쓰는 업무 화면이 아니라 **상자 하나가
 * 한가운데 서는 화면**이라, 1920×1080 단말에서는 남는 자리가 그대로 여백이 되어 설치
 * 담당자가 서서 보기에 작았다(실기 실측 2026-09-12 · 사용자 지적).
 *
 * ⛔ **글자·버튼 크기를 따로 키우지 않는다.** 값을 하나씩 올리면 상자 안의 크기 관계가
 *    어긋난다. 배율 하나로 키우면 글자·버튼·여백·터치 크기가 «같은 비율로» 커진다.
 *
 * ⚠ **업무 화면은 건드리지 않는다** — 이 배율은 `.pop-registration__card` 에만 걸린다.
 */

/**
 * **상자 기준 예산.** 화면 전체 예산(`pop-fit` 의 1024×768)을 그대로 쓰면 세로가 배율을
 * 정하는데, 이 화면은 상자 하나뿐이라 세로를 다 쓰지 않는다 — 그만큼 덜 커진다(실측
 * 1920×1080 에서 1.41배 · 사용자 지적 「좀 더 커도 된다」). 그래서 «상자가 차지할 자리»로
 * 잰다.
 *
 * - 가로: 상자 상한 `1040` + 좌우 여백 `48` 씩 = `1136`
 * - 세로: 가장 긴 상태(확인 사실표 + 버튼)가 서는 높이에 숨 쉴 자리를 더한 `640`
 */
const WIDTH_BUDGET = 1136;
const HEIGHT_BUDGET = 640;

/**
 * 상한 — 이 이상은 키우지 않는다. 아주 큰 화면에서 글자만 무한정 커지면 사유 문구가 상자를
 * 넘겨 상자 안 스크롤이 생긴다.
 */
const MAX_SCALE = 2;

/**
 * ⛔ **1 보다 작아지지 않는다.** 화면이 예산보다 작을 때 줄이는 것은 `pop-fit` 의 몫이고,
 *    여기서 또 줄이면 두 배율이 곱해져 글자가 읽히지 않는다.
 */
export const panelScale = (width: number, height: number): number => {
  if (width <= 0 || height <= 0) return 1;

  const scale = Math.min(width / WIDTH_BUDGET, height / HEIGHT_BUDGET);

  return Math.min(MAX_SCALE, Math.max(1, scale));
};
