/**
 * 불합격 처분 — **잠정 선택이다.**
 *
 * ⛔ **고른 값을 서버로 보내지 않는다.** 확정 판정은 불량창고 입고 «후» 별도 화면이 한다
 * (✅REQ-PR-0025 · 스펙 §5-8). 여기서 저장하면 **정본이 둘이 되고**, 뒤에 오는 확정이
 * 앞의 잠정값과 어긋나도 어느 쪽이 옳은지 화면이 말할 수 없다.
 *
 * ⛔ **자동으로 고르지 않는다.** 「재작업 가능 / 폐기」를 가르는 속성이 불량코드에 아직
 * 없다(스펙 §5-8 · 미결 6). 규칙을 지어내면 설계가 승인한 적 없는 판정이 화면에 굳는다 —
 * **사람이 고른다.**
 *
 * 그러면 왜 칸을 두는가 — 검사자가 현장에서 판단한 것을 **화면에 남겨 다음 사람이 보게**
 * 하기 위해서다. 자리를 감추면 협의가 끝나 규칙이 왔을 때 사용자가 「없던 것이 생겼다」로
 * 만난다. 자리를 미리 보여 두면 「아직 저장되지 않는다」로 만난다.
 *
 * 이 화면이 소유한다 — 다른 화면 슬라이스의 같은 이름 파일을 참조하지 않는다.
 */

/**
 * 고를 수 있는 값 둘. ⚠ **공통코드 조회로 채우지 않는다** — 저장하지 않는 값이라 서버가
 * 아는 코드일 필요가 없고, 조회를 얹으면 그 조회의 실패가 저장되지도 않는 칸 때문에
 * 화면을 막는다. 값이 실제로 저장되는 날 그때 조회로 바꾼다.
 */
export type DispositionChoice = 'REWORK' | 'SCRAP';

/** 아직 고르지 않았다. **고르지 않은 것이 정상 상태다** — 처분 미선택은 확정을 막지 않는다. */
export type DispositionState = DispositionChoice | null;

/**
 * 처분을 고를 수 있는가 — **불합격수량이 있을 때만이다.**
 *
 * 불합격이 0인데 처분을 고르게 두면 「무엇에 대한 처분인가」가 없는 값이 남는다.
 *
 * ⚠ **셀 수 없는 상태에서는 열지 않는다.** 수량 칸에 수량이 아닌 값이 남아 있으면 불합격이
 * 얼마인지 화면이 모르는 것이지 0인 것이 아니다 — 그때 열면 「0인데 열린」 자리가 된다.
 */
export const canChooseDisposition = (rejectedMicro: bigint | null): boolean =>
  rejectedMicro !== null && rejectedMicro > 0n;

/**
 * 고를 수 없게 된 선택을 거둔다.
 *
 * ⭐ **불합격이 0으로 바뀌면 앞서 고른 값이 남지 않는다.** 남겨 두면 화면에는 안 보이는데
 * 값은 살아 있어, 불합격을 다시 올렸을 때 사용자가 고르지 않은 처분이 되살아난다.
 */
export const settleDisposition = (
  current: DispositionState,
  rejectedMicro: bigint | null,
): DispositionState => (canChooseDisposition(rejectedMicro) ? current : null);
