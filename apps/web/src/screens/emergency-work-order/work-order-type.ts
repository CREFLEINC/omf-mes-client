/**
 * 긴급을 뜻하는 W/O 유형 코드.
 *
 * ⛔ **빈 값은 「유형을 안 붙인다」가 아니라 「아직 모른다」다.** 계약이 이 자리의 값을
 * 정하지 않았고(설명은 「NORMAL 기본」, 예시는 자리표시), 설계 저장소에 물어 두었다.
 *
 * ⛔ **값을 지어내지 않는다.** 그리고 **모른다고 필드를 빼지도 않는다** — 빼면 서버 기본값이
 * 붙어 화면은 「유형: 긴급」이라 적어 놓고 양산 W/O 를 만든다. 거부당하는 것보다 나쁘다.
 * 오류가 나지 않아 아무 데서도 안 보이고, 그렇게 만들어진 W/O 는 긴급으로 세어지지 않는다.
 *
 * 그래서 값이 비어 있는 동안은 **발행 자체를 잠근다**(감추지 않고 사유와 함께 — G-2).
 * 값이 오면 **이 상수 한 줄만 채우면** 열린다.
 */
export const EMERGENCY_WORK_ORDER_TYPE_CODE = '';

/**
 * 유형 코드를 아는가.
 *
 * 상수를 직접 읽지 않고 인자로도 받는 이유는, 값이 온 뒤의 동작을 **값이 오기 전에**
 * 확인해 두기 위해서다. 상수만 읽으면 열린 쪽 경로는 회신이 와야 처음 실행된다.
 */
export const isEmergencyTypeCodeKnown = (code: string = EMERGENCY_WORK_ORDER_TYPE_CODE): boolean =>
  code.trim() !== '';
