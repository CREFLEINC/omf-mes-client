/**
 * 긴급을 뜻하는 W/O 유형 코드.
 *
 * ⛔ **이 칸을 비우고 보내지 않는다.** 비우면 서버가 기본값(양산)으로 채워, 화면은 「유형:
 * 긴급」이라 적어 놓고 **양산 W/O 를 만든다.** 거부당하는 것보다 나쁘다 — 오류가 나지 않아
 * 아무 데서도 안 보이고, 그렇게 만들어진 W/O 는 긴급으로 세어지지도, 긴급 현장 투입 화면의
 * 목록에 뜨지도 않는다.
 *
 * ⛔ **값을 여기 한 곳에만 둔다.** 로직 곳곳에 문자열을 박으면 값이 바뀔 때 일부만 고쳐지고,
 * 그 어긋남 역시 오류 없이 조용하다. 발행 본문도 이어받기 조회도 이 상수를 참조한다.
 *
 * 값 집합은 셋이다 — 양산 · **긴급** · 재작업. 이 화면은 그중 하나만 쓴다(설계 근거:
 * omf-mes#259 회신 · 반영 omf-mes#274).
 */
export const EMERGENCY_WORK_ORDER_TYPE_CODE = 'EMERGENCY';

/**
 * 유형 코드를 아는가.
 *
 * ⚠ **값이 정해진 뒤에도 남겨 둔다.** 이 화면은 유형을 실어야만 성립하므로, 어떤 경위로든
 * 빈 값이 흘러들면 **발행이 열려서는 안 된다** — 상수를 채운 것과 「빈 값으로는 못 보낸다」는
 * 다른 보장이고, 뒤엣것은 계속 필요하다.
 *
 * 상수를 직접 읽지 않고 인자로도 받는 이유는 그 닫힌 쪽 경로를 감지기가 확인할 수 있게
 * 하기 위해서다.
 */
export const isEmergencyTypeCodeKnown = (code: string = EMERGENCY_WORK_ORDER_TYPE_CODE): boolean =>
  code.trim() !== '';
