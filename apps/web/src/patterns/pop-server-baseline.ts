/**
 * **이 빌드가 보는 서버가 임시 구현 기준선(v0.1.2)인가.**
 *
 * 서버는 아직 만드는 중이고, 전달본(`docs/client-api/2026-09-11`)이 옮겨 적은 것은 그 «지금»이다.
 * 우리가 고정한 설계(2026-09-08)에는 있는 질의 축이 전달본에는 없는 자리가 있어, 같은 화면이
 * **어느 서버를 보느냐에 따라 할 수 있는 일이 다르다**(#1095).
 *
 * ⭐ **목은 고정 설계대로 답한다.** 개발 서버(`pnpm dev:pop`)와 시험이 보는 것이 그것이라,
 * 그 두 곳에서는 화면이 설계대로 선다 — 축을 지우면 목으로 도는 시험에서 그 흐름을 한 번도
 * 확인할 수 없게 된다(전례: 라벨 렌디션 · #1083).
 *
 * ⛔ **배포본만 좁힌다.** 실서버는 없는 축을 **거부하지 않고 무시한다** — 그래서 「조금 부정확한
 * 목록」이 아니라 **좁혀지지 않은 전체 목록**이 조용히 서고, 그 목록에서 고른 것으로 되돌릴 수
 * 없는 발행이 나간다. 침묵하는 실패라 육안으로 잡히지 않는다.
 *
 * ⚠ **`import.meta.env.DEV` 를 쓰지 않는다.** POP 확인용 설치본은 `--mode development` 로 굽고,
 * 그 산출물에서 `DEV` 는 거짓이라 근거가 되지 못한다. 가름은 `MODE` 한 표기뿐이고 빌드 시점에
 * 상수로 접힌다.
 *
 * ⚠ **전달본은 임시다.** 설계팀 확정본이나 서버 구현이 축을 되돌리면 이 파일을 고치지 말고
 * **호출부의 사용을 걷는다** — 그때 무엇이 왜 좁혀져 있었는지가 호출부에 남아 있어야 한다.
 */
export const isServerBaselineBuild = (): boolean => import.meta.env.MODE === 'production';
