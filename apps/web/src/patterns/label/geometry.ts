/**
 * 라벨을 재는 **자** — 해상도와 종이 크기.
 *
 * ⭐ **자가 갈리면 한쪽이 종이를 벗어난다.** POP 단말들은 같은 라벨 프린터에 같은 라벨지를
 *    물려 쓴다. 자재 LOT · 출고 QR · 포장 · 납품 라벨이 저마다 제 dpi 와 제 종이 크기를 적어
 *    두면, 그중 하나가 어긋났을 때 **그 라벨만 잘려 나오고** 그 사실은 실기에서야 드러난다.
 *    그래서 자는 한 곳에 둔다.
 *
 * ⚠ **같은 수가 저장소 밖에도 있다** — 씨앗 서버의 `tools/mock/label-layout.mjs` 와 실물 TSPL
 *   을 짜는 `apps/pop/src/main/tspl-label.ts`. **여기를 고치면 그 둘도 함께 본다.**
 *
 * ⛔ **여백·글줄 자리를 여기 두지 않는다.** 그것은 라벨 «한 종류»의 서식이라 화면이 갖는다.
 *    여기 있는 것은 「어느 라벨이든 같아야 하는 것」뿐이다.
 */

/** 203dpi — 현장 라벨 프린터의 해상도. */
export const DPI = 203;

/** 밀리미터를 점 수로. 점은 정수라 반올림한다. */
export const mm = (value: number): number => Math.round((value / 25.4) * DPI);

/**
 * 서식 크기 80 × 30 mm(사양서 §5.4). 라벨지(대지) 크기와는 다른 축이다.
 *
 * ⚠ 서식이 종이보다 크면 프린터가 조용히 자른다 — 앱은 성공으로 보고한다.
 */
export const LABEL_WIDTH = mm(80);
export const LABEL_HEIGHT = mm(30);
