/**
 * POP 터치 타겟 등급 — **치수를 제품이 임시로 채우는 자리**다.
 *
 * 터치 단말의 버튼 크기는 네 등급으로 정해져 있는데(일반 56↑ / 주요 64↑ / 핵심 64~72 /
 * 위험 72↑), 우리가 고정해 쓰는 디자인 시스템 커밋의 `Button`은 `xl`(60px)까지다 —
 * **일반 등급까지만 덮는다.** 나머지 셋은 부족분을 제품이 채운다(착수 이슈 #139 6항).
 *
 * ⛔ **픽셀 값을 여기에 적지 않는다.** 실제 치수는 `app/app.css`의 `.pop-touch-*` 한 곳에
 * 있고 이 파일은 등급을 그 클래스로 옮기기만 한다. 두 곳에 적으면 한쪽만 고쳐진다.
 *
 * 디자인 시스템이 72px 변형을 내려 주면 이 모듈과 짝이 되는 CSS를 함께 걷어낸다 —
 * 화면 파일은 등급 이름만 쓰므로 걷어낼 때 화면을 건드리지 않는다.
 */

/**
 * 무엇을 누르는가로 등급이 갈린다. 「얼마나 큰가」가 아니라 「틀렸을 때 무엇이 일어나는가」다.
 *
 * - `normal` 목록 행·보조 조작 — 되돌리기 쉽다
 * - `primary` 화면의 주 조작 — 흐름을 진행시킨다
 * - `critical` 기록을 남기는 조작 — 되돌리려면 다른 조작이 필요하다
 * - `destructive` 되돌릴 수 없는 조작
 */
export type PopTouchGrade = 'normal' | 'primary' | 'critical' | 'destructive';

/**
 * 등급에 해당하는 클래스 이름. 화면은 이 함수만 쓰고 클래스 이름을 직접 적지 않는다 —
 * 직접 적으면 등급 이름이 화면마다 달라지고, 걷어낼 때 무엇을 지울지 셀 수 없다.
 */
export const popTouchClass = (grade: PopTouchGrade): string => `pop-touch pop-touch-${grade}`;
