import { describe, expect, it } from 'vitest';

import { pressKey } from './numeric-keypad';

/**
 * 키 하나가 값에 반영되는 규칙 — 공유계약 D-4 부품.
 *
 * ⚠ **뒤에 검증이 또 있다고 여기서 느슨하게 두지 않는다.** 사용처마다 검증 규칙이 다르고
 * (사번은 정수·고정 자릿수, 수량은 소수), 이 부품은 그 전부의 앞에 선다 — 여기서 새면
 * 각 화면이 같은 것을 따로 막아야 한다.
 */
describe('pressKey', () => {
  it('숫자를 뒤에 잇는다', () => {
    expect(pressKey('', '1')).toBe('1');
    expect(pressKey('1', '2')).toBe('12');
  });

  /*
   * ⛔ **소수점을 둘 이상 받지 않는다.** `1.2.3`은 어떤 사용처에서도 유효하지 않고, 각 화면의
   * 검증에 맡기면 작업자는 **다 치고 나서야** 틀린 것을 안다.
   */
  it('소수점은 한 번만 받는다', () => {
    expect(pressKey('1.2', '.')).toBe('1.2');
    expect(pressKey('12', '.')).toBe('12.');
  });

  /* 빈 값에서 소수점을 누르면 `.5`가 아니라 `0.5`가 된다 — 앞이 빈 소수는 읽기 어렵다. */
  it('빈 값에서 소수점을 누르면 0을 앞세운다', () => {
    expect(pressKey('', '.')).toBe('0.');
  });

  /*
   * ⛔ **앞자리 0을 쌓지 않는다.** `007`은 `7`과 같은 수인데 글자가 달라, 되돌릴 수 없는
   * 기록에 실리면 나중에 같은 값인지 눈으로 판단해야 한다.
   */
  it('앞자리 0을 쌓지 않는다', () => {
    expect(pressKey('0', '7')).toBe('7');
    expect(pressKey('0', '0')).toBe('0');
  });

  /* 다만 `0.`은 0이 뜻을 갖는 자리다 — 소수를 치는 중이므로 지우지 않는다. */
  it('소수를 치는 중의 0은 남긴다', () => {
    expect(pressKey('0.', '5')).toBe('0.5');
  });
});
