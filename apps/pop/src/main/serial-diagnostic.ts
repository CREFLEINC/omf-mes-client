/**
 * 실기 진단 — **직렬 포트로 프린터가 대답하는지 사람이 눈으로 확인하는 자리**(#831).
 *
 * ⭐ **왜 필요한가.** 이 경로에는 우리가 실기에서만 알 수 있는 것이 셋 있다 — 프린터가 잡힌
 *   포트 이름, 프린터 쪽 통신 설정(속도·패리티·흐름 제어), 그리고 **TSPL 로 보내면 정말
 *   찍히는가**. 셋 다 코드로는 잴 수 없고, 서버가 명령형을 내려 주기 전까지는 화면을 눌러서도
 *   닿지 않는다. 그래서 서버 없이 포트만으로 한 장을 찍어 보는 길을 둔다.
 *
 * ⛔ **여기서 만드는 것은 「업무 라벨」이 아니다.** 고정된 시험 문구뿐이고, 발행 기록·LOT·품번
 *    같은 업무 자료가 실리지 않는다. 실제 라벨의 서식은 그대로 서버 소관이며(설계 결정 18),
 *    이 파일이 그 자리를 대신하지 않는다 — 여기 담긴 것이 늘어나기 시작하면 그것이 곧
 *    「셸이 서식을 갖는다」가 된다. 시험 문구 밖의 값을 이 파일에 넣지 않는다.
 *
 * ⚠ **명령은 CRLF 로 끝난다.** TSPL 은 줄 단위로 읽고 `\n` 만으로는 끊기지 않는 기종이 있다.
 */

/** 시험할 라벨 규격. #831 이 대상으로 든 두 가지다. */
export type TestLabelSize = '80x30' | '100x60';

/** 규격별 대지 크기(mm). 라벨을 바꿔 끼우고 각각 확인한다. */
const SIZES: Record<TestLabelSize, { width: number; height: number }> = {
  '80x30': { width: 80, height: 30 },
  '100x60': { width: 100, height: 60 },
};

/**
 * 시험 라벨 한 장. **글자와 바코드가 함께 있다** — 완료 조건이 규격대로 찍히는 것과
 * 바코드가 스캐너에 읽히는 것을 함께 요구하므로, 한 장으로 둘 다 본다.
 *
 * ⚠ 바코드 내용을 영문·숫자로 둔다. 프린터 내장 폰트로 한글·베트남어를 찍는 것은 별개
 *   문제이고, 라벨 사양이 「영문·숫자만」으로 정해져 있다.
 */
export function buildTestLabel(size: TestLabelSize): string {
  const { width, height } = SIZES[size];

  return (
    [
      `SIZE ${String(width)} mm,${String(height)} mm`,
      'GAP 2 mm,0 mm',
      'DIRECTION 1',
      'CLS',
      `TEXT 30,30,"3",0,1,1,"OMF-MES TEST ${size}"`,
      'TEXT 30,80,"2",0,1,1,"SERIAL PORT CHECK"',
      `BARCODE 30,120,"128",60,1,0,2,2,"OMFTEST${size.replace('x', 'X')}"`,
      'PRINT 1',
    ].join('\r\n') + '\r\n'
  );
}
