/** 글자 한 칸의 점 수. 폭·높이 계산이 전부 이 둘에서 나온다. */
export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** 글자 사이 빈 칸(점). 0 이면 글자가 붙어 읽기 어렵다. */
export const GLYPH_GAP = 1;

/** 없는 글자는 **빈칸으로 흘리지 않고** 채운 사각형으로 낸다 — 빠진 사실이 눈에 보여야 한다. */
const MISSING = '#####|#...#|#.#.#|#...#|#.#.#|#...#|#####';

export function glyphRows(character) {
  const key = character.toUpperCase();
  return (GLYPHS[key] ?? MISSING).split('|');
}

/** 이 글꼴로 문자열을 그렸을 때의 점 너비. 자리 배치에 쓴다. */
export function textDots(text) {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP;
}
